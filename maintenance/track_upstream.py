"""Mirror upstream source/releases and maintain one review proposal.

Never execute upstream code, move existing version tags or modify local apps.
Authentication is supplied to gh; release downloads are generated by GitHub.
"""
from __future__ import annotations

import argparse
import html
import json
import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import quote, urlencode

# Support both direct execution and importlib-based regression tests.
sys.path.insert(0, str(Path(__file__).resolve().parent))
from run_records import sanitize

REPOSITORY = "KATOUIV/claude-desktop-zh-cn"
UPSTREAM = "javaht/claude-desktop-zh-cn"
BASE = "katou/windows-compat"
BEGIN = "<!-- upstream-tracking:start -->"
END = "<!-- upstream-tracking:end -->"


class TrackingError(RuntimeError):
    def __init__(self, code):
        self.code = code
        super().__init__(code)


class GitHub:
    @staticmethod
    def run(command, payload=None):
        try:
            result = subprocess.run(command, input=payload, capture_output=True, text=True, encoding="utf-8", timeout=90)
        except subprocess.TimeoutExpired:
            raise TrackingError("github_timeout") from None
        if result.returncode:
            # Inspect in memory only. Never expose raw gh stderr in reports/tracebacks.
            detail = result.stderr.lower()
            code = "github_command_failed"
            if "diverged" in detail or "not possible to fast-forward" in detail:
                code = "mirror_diverged"
            elif "rate limit" in detail:
                code = "github_rate_limited"
            elif "http 401" in detail or "not logged" in detail:
                code = "github_auth_failed"
            elif "http 403" in detail or "resource not accessible" in detail:
                code = "github_permission_denied"
            elif "http 404" in detail:
                code = "github_not_found"
            raise TrackingError(code)
        return result.stdout

    def sync(self):
        # gh rejects a divergent mirror by default. Never pass --force.
        self.run(["gh", "repo", "sync", REPOSITORY, "--source", UPSTREAM, "--branch", "main"])

    def api(self, endpoint, method="GET", data=None, missing_ok=False):
        command = ["gh", "api", "--method", method, endpoint]
        if data is not None:
            command += ["--input", "-"]
        try:
            return json.loads(self.run(command, json.dumps(data) if data is not None else None))
        except TrackingError as error:
            if missing_ok and method == "GET" and error.code == "github_not_found":
                return None
            raise


def sync_release(client, release, mirror_sha):
    """Mirror the official tag, never package local files or retag Fork changes."""
    tag = release["tag_name"]
    if not re.fullmatch(r"v?[0-9]+\.[0-9]+\.[0-9]+", tag) or release.get("draft") or release.get("prerelease"):
        raise ValueError("Expected a stable upstream release")
    encoded = quote(tag, safe="")
    commit = client.api(f"repos/{UPSTREAM}/commits/{encoded}")["sha"]
    ancestry = client.api(f"repos/{REPOSITORY}/compare/{commit}...{mirror_sha}")
    if ancestry["status"] not in {"ahead", "identical"}:
        raise ValueError("Release commit is outside the fast-forward mirror")
    existing_tag = client.api(f"repos/{REPOSITORY}/git/ref/tags/{encoded}", missing_ok=True)
    if existing_tag:
        obj = existing_tag["object"]
        existing_sha = obj["sha"] if obj["type"] == "commit" else client.api(f"repos/{REPOSITORY}/commits/{encoded}")["sha"]
        if existing_sha != commit:
            raise ValueError("Existing release tag differs; never move it")
    existing = client.api(f"repos/{REPOSITORY}/releases/tags/{encoded}", missing_ok=True)
    if existing:
        if existing.get("draft") or existing.get("prerelease"):
            raise ValueError("Existing release requires review")
        return existing["html_url"]
    upstream_url = f"https://github.com/{UPSTREAM}/releases/tag/{encoded}"
    body = (f"同步自 [上游 {tag}]({upstream_url})，原始提交 `{commit}`。\n\n"
            "下方 Source code 为上游原版源码；安装方法、兼容范围及附加文件见上游发布说明。\n\n"
            f"需要本 Fork 补充修复时，下载 [维护分支 ZIP](https://github.com/{REPOSITORY}/archive/refs/heads/{BASE}.zip)"
            " 并先查看包内维护说明；该分支与原版标签分别管理。仓库发布不代表客户端已完成适配。\n")
    created = client.api(f"repos/{REPOSITORY}/releases", "POST", {
        "tag_name": tag, "target_commitish": commit, "name": tag,
        "body": body, "draft": False, "prerelease": False, "make_latest": "true"})
    return created["html_url"]


def replace_block(body, block):
    """Replace only our own machine-written section; retain human review notes."""
    if BEGIN not in body and END not in body:
        return body.rstrip() + ("\n\n" if body.strip() else "") + block
    if body.count(BEGIN) != 1 or body.count(END) != 1 or body.index(BEGIN) > body.index(END):
        raise ValueError("Ambiguous tracking markers; preserve review text and stop")
    start, finish = body.index(BEGIN), body.index(END) + len(END)
    return body[:start] + block + body[finish:]


def track(client, repository=REPOSITORY):
    if repository != REPOSITORY:
        raise ValueError("Tracking writes are restricted to the configured personal Fork")
    client.sync()  # A failure must stop all subsequent API mutations.
    release = client.api(f"repos/{UPSTREAM}/releases/latest")
    mirror_sha = client.api(f"repos/{REPOSITORY}/git/ref/heads/main")["object"]["sha"]
    compare = client.api(f"repos/{REPOSITORY}/compare/katou%2Fwindows-compat...{mirror_sha}")
    pending = int(compare["ahead_by"])
    report = {"status": "current" if pending == 0 else "review_needed", "release": release["tag_name"],
              "release_url": release["html_url"], "mirror_sha": mirror_sha,
              "pending_commits": pending, "compatibility_only_commits": compare["behind_by"]}
    if pending == 0:
        report["fork_release_url"] = sync_release(client, release, mirror_sha)
        return report

    matches = []
    page = 1
    while True:
        query = urlencode({"state": "open", "base": BASE, "per_page": 100, "page": page})
        prs = client.api(f"repos/{REPOSITORY}/pulls?{query}")
        matches.extend(pr for pr in prs if pr.get("head", {}).get("ref") == "main"
                       and (pr["head"].get("repo") or {}).get("full_name") == REPOSITORY)
        if len(prs) < 100:
            break
        page += 1
    if len(matches) > 1:
        raise ValueError("Multiple upstream review PRs exist; stop instead of creating a duplicate")

    files = compare.get("files", [])
    names = "\n".join("- <code>" + html.escape(f["filename"]) + "</code>" for f in files[:30])
    block = (f"{BEGIN}\n## 自动上游追踪\n\n"
             f"正式 Release：[{release['tag_name']}]({release['html_url']})。\n\n"
             f"镜像提交：`{report['mirror_sha']}`；待审上游提交：{pending}。\n\n"
             f"相关文件（最多显示 30 个，完整差异见 PR Files changed）：\n{names}\n\n"
             "仅为同步提案；main 可能含未发布改动。审阅并确认 Windows/Linux 必需检查通过后，按保护规则合并。"
             "客户端适配和安装另行验证。\n"
             f"{END}")
    if matches:
        pr = matches[0]
        body = replace_block(pr.get("body") or "", block)
        if body != (pr.get("body") or ""):
            client.api(f"repos/{REPOSITORY}/pulls/{pr['number']}", "PATCH", {"body": body})
    else:
        pr = client.api(f"repos/{REPOSITORY}/pulls", "POST", {
            "title": "审阅上游更新（保留 Windows 兼容修复）", "head": "main", "base": BASE,
            "draft": True, "body": block})
    report["pull_request"] = pr["html_url"]
    report["fork_release_url"] = sync_release(client, release, mirror_sha)
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", required=True)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--summary", type=Path, required=True)
    parser.add_argument("--run-id")
    args = parser.parse_args()
    try:
        report = track(GitHub(), args.repository)
    except Exception as error:
        code = error.code if isinstance(error, TrackingError) else "invalid_tracking_state" if isinstance(error, (ValueError, KeyError, TypeError)) else "tracking_failed"
        report = {"status": "failed", "error_code": code}
    report = sanitize({**report, "run_id": args.run_id})
    try:
        args.report.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        args.summary.write_text("## Upstream tracking\n\n```json\n" + json.dumps(report, ensure_ascii=False, indent=2)
                                + "\n```\n", encoding="utf-8")
    except Exception:
        print("Upstream tracking failed: report_write_failed", file=sys.stderr)
        raise SystemExit(1) from None
    if report["status"] == "failed":
        print(f"Upstream tracking failed: {report['error_code']}; fingerprint={report['fingerprint']}", file=sys.stderr)
        raise SystemExit(1) from None
    print(json.dumps(report, ensure_ascii=False))


if __name__ == "__main__":
    main()
